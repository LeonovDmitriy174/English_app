// session.js — правила одного захода на повторение. Чистые функции, проверяются в Node.
//
// Зачем. Слово на низких уровнях возвращается через минуту и через десять минут, то есть внутри
// того же захода. Если засчитывать каждый верный ответ, слово за пару минут «взлетает» с первого
// уровня на третий-четвёртый, хотя вы его ещё ни разу не вспоминали с перерывом. Поэтому:
//
//   - за один заход слово поднимается максимум на один уровень;
//   - верный ответ приносит рост только если в этом заходе по слову ещё не было ни роста, ни ошибки;
//   - ошибка работает как обычно (сброс), а слово возвращается в этот же заход, чтобы закрепить ответ,
//     но повторный верный ответ после ошибки уровень уже не поднимает;
//   - слово, на которое ответили верно с первого раза, в этот заход не возвращается.

export const MAX_RETRIES = 2;
export const newTracker = () => new Map();

/**
 * Что делать с ответом. result: 'ok' | 'near' | 'no'.
 * Возвращает { effective, requeue }: какой результат записать в уровень и вернуть ли слово в этот заход.
 */
export function judgeInSession(tracker, id, result) {
  const st = tracker.get(id) || { raised: false, failed: false, asked: 0 };
  let effective = result;
  let requeue = false;
  if (result === "no") {
    st.failed = true;
    st.asked += 1;
    requeue = st.asked <= MAX_RETRIES; // не мучаем бесконечно: после двух возвратов слово оставляем до следующего захода
  } else if (result === "ok") {
    if (st.raised || st.failed) effective = "near"; // уже учтено в этом заходе: уровень не меняем
    else st.raised = true;
  }
  tracker.set(id, st);
  return { effective, requeue };
}

/** Куда вставить возвращаемое слово: через `gap` других карточек (или в конец, если их меньше). */
export function requeuePosition(nextIndex, length, gap = 3) {
  return Math.min(length, nextIndex + gap);
}
