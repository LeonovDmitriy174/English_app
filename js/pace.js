// pace.js — скрытое правило скорости. Чистые функции без DOM, проверяются в Node (tests/pace.test.mjs).
//
// Верный, но очень медленный ответ говорит о том, что слово вспоминалось с трудом: уровень такому ответу не растёт,
// слово вернётся через тот же срок. Быстрый верный ответ поднимает слово как обычно.
// Время пользователю не показывается нигде: ни в заданиях, ни в итогах. Правило можно выключить в настройках словаря.
//
// Пороги щедрые: в них входит чтение вопроса, раздумье и сам набор текста (для письменных заданий порог растёт с длиной ответа).
// Диктант не измеряется: сколько занимает прослушать и записать предложение, зависит от предложения.

/** Базовый порог в миллисекундах и надбавка за каждую букву ответа. */
export const LIMITS = {
  choice: { base: 10000 },
  choiceBack: { base: 10000 },
  listenChoice: { base: 12000 },
  clozeChoice: { base: 15000 },
  phraseChoice: { base: 12000 },
  formChoice: { base: 15000 },
  spell: { base: 12000, perChar: 700 },
  cloze: { base: 16000, perChar: 700 },
  listenType: { base: 14000, perChar: 700 },
};

/** Порог для задания; null, если для него скорость не измеряется. len — длина ожидаемого ответа в буквах. */
export function slowLimit(task, len = 0) {
  const l = LIMITS[task];
  return l ? l.base + (l.perChar || 0) * Math.max(0, len) : null;
}

/** Медленно ли ответили. Неизвестное время (приложение сворачивали) медленным не считается. */
export const isSlow = (task, ms, len = 0) => {
  const limit = slowLimit(task, len);
  return limit != null && Number.isFinite(ms) && ms > limit;
};

/** Итог ответа с учётом скорости: медленное «верно» превращается в «почти» (уровень не меняется). */
export const applyPace = (result, task, ms, { len = 0, enabled = true } = {}) => (enabled && result === "ok" && isSlow(task, ms, len) ? "near" : result);
