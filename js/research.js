// research.js — цифры исследования Пола Нейшна для экрана «Топ слов по частотности»: какую долю слов текста узнаёт читатель,
// если знает N самых частых семей слов. Чистые функции и данные без DOM (tests/research.test.mjs), оформление в js/views/research.js.
//
// Источник: Paul Nation, «How large a vocabulary is needed for reading and listening?» (2006), таблица 5: роман Lady Chatterley's Lover,
// накопленный охват текста списками семей слов по тысячам; имена собственные учтены как знакомые (в статье это допущение: у них минимальная
// цена изучения). Семья слов это основное слово со всеми формами и производными: accept, accepted, acceptable, acceptance.
// Порог в статье: 98% текста (одно незнакомое слово из 50), с него, по расчётам автора, большинство читателей понимают текст; при 95% (одно из 20)
// понимают лишь немногие. 98% достигается на 8–9 тысячах семей слов для письменного текста и на 6–7 тысячах для речи.
// Сами списки, из которых собран «Топ слов по частотности», это BNC/COCA word family lists того же автора.

/** Сколько семей слов знает читатель → какая доля слов романа ему знакома (%). */
export const STOPS = [
  { n: 1000, cover: 82.93 },
  { n: 2000, cover: 90.14 },
  { n: 3000, cover: 93.28 },
  { n: 5000, cover: 96.13 },
  { n: 7000, cover: 97.43 },
  { n: 9000, cover: 98.22 },
];
export const THRESHOLD = 98; // процент охвата, с которого читатели в исследовании понимали текст
export const DEFAULT_STOP = 3; // какая отметка открыта сразу: 5000
export const STRIP = 50; // сколько слов показывает полоска (порог тоже считается «из 50»)

/** «Одно незнакомое слово из N»: N по доле известных слов. */
export const oneIn = (cover) => Math.round(100 / (100 - cover));

/** Сколько незнакомых слов приходится на каждые STRIP слов (не меньше одного: всегда что-то незнакомое найдётся). */
export const unknownOf = (cover, of = STRIP) => Math.max(1, Math.round((of * (100 - cover)) / 100));

/** Номера клеток полоски, в которых стоят незнакомые слова: поровну по всей длине, а не кучкой с краю. */
export function unknownCells(count, of = STRIP) {
  return Array.from({ length: count }, (_, j) => Math.floor(((j + 0.5) * of) / count));
}
